#!/usr/bin/env node
/*
 * docs/tools.md is generated from the built server, so it cannot drift from the tools that really exist.
 *
 *   node scripts/gen-tools-doc.mjs           write docs/tools.md
 *   node scripts/gen-tools-doc.mjs --check   exit 1 when docs/tools.md is out of date, or when any doc names a
 *                                            dotted tool (desktop.click, browser.open...) that the server does not register
 *
 * Needs `npm run build` first.
 */
import { spawn } from "node:child_process";
import { mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const entry = path.join(root, "packages/mcp-server/dist/index.js");
const target = path.join(root, "docs/tools.md");
const check = process.argv.includes("--check");

function listTools(profile) {
  const home = mkdtempSync(path.join(os.tmpdir(), "osseo-tools-doc-"));
  return new Promise((resolve, reject) => {
    const server = spawn(process.execPath, [entry], { stdio: ["pipe", "pipe", "ignore"], env: { ...process.env, OSSEO_HOST: "0", OSSEO_TOOLS_PROFILE: profile, OSSEO_HOME: home, OSSEO_CONFIG: path.join(home, "config.json"), DISPLAY: "" } });
    let buffer = "";
    const done = (value, error) => { server.kill(); rmSync(home, { recursive: true, force: true }); if (error) reject(error); else resolve(value); };
    const timer = setTimeout(() => done(undefined, new Error("the server did not answer tools/list")), 20_000);
    server.stdout.on("data", (chunk) => {
      buffer += chunk;
      for (const line of buffer.split("\n")) {
        let message; try { message = JSON.parse(line); } catch { continue; }
        if (message.id === 2) { clearTimeout(timer); done(message.result.tools); }
      }
    });
    const send = (body) => server.stdin.write(`${JSON.stringify({ jsonrpc: "2.0", ...body })}\n`);
    send({ id: 1, method: "initialize", params: { protocolVersion: "2024-11-05", capabilities: {}, clientInfo: { name: "gen-tools-doc", version: "1" } } });
    setTimeout(() => { send({ method: "notifications/initialized" }); send({ id: 2, method: "tools/list" }); }, 500);
  });
}

const firstSentence = (text) => { const one = String(text ?? "").replace(/\s+/g, " ").trim(); const cut = one.search(/\.\s/); return cut > 0 ? one.slice(0, cut + 1) : one; };
const inputs = (tool) => Object.keys(tool.inputSchema?.properties ?? {}).filter((key) => key !== "dryRun" && key !== "confirmationToken").map((key) => (tool.inputSchema?.required ?? []).includes(key) ? `**${key}**` : key).join(", ");
const esc = (text) => text.replace(/\|/g, "\\|");
const family = (name) => name.includes(".") ? name.split(".")[0] : "numbered";

const FAMILIES = {
  numbered: "Numbered actions (the default set)", guide: "Guide mode", desktop: "Desktop input and capture", screen: "Screen reading", window: "Windows",
  ui: "Accessibility tree", app: "Apps and links", browser: "The agent's own browser (and the person's, through the extension)", file: "Files", shell: "Shell",
  clipboard: "Clipboard", computer: "Waits, state and plans", task: "Tasks", agent: "Stop, pause and hand-off", workflow: "Saved workflows",
  memory: "Lessons", vision: "Vision helpers", system: "System"
};

function render(desktop, full) {
  const lines = [
    "# Tools",
    "",
    "<!-- Generated by scripts/gen-tools-doc.mjs from the built server. Do not edit by hand; run `npm run docs:tools`. -->",
    "",
    `Osseo registers ${full.length} tools. Clients see the **${desktop.length}-tool default set** below (\`tools.profile: "desktop"\`).`,
    "Every other tool stays callable by name; set `tools.profile: \"full\"` (or `OSSEO_TOOLS_PROFILE=full`) to list them all.",
    "Each call passes the same safety path: schema check, Stop and pause gates, a preview, an approval when the action is consequential, then the audit log.",
    "",
    "## Default set",
    "",
    "| Tool | What it does | Inputs (bold = required) |",
    "|---|---|---|",
    ...desktop.map((tool) => `| \`${tool.name}\` | ${esc(firstSentence(tool.description))} | ${esc(inputs(tool)) || "none"} |`),
    "",
    "## All tools",
    ""
  ];
  const groups = new Map();
  for (const tool of full) { const key = family(tool.name); if (!groups.has(key)) groups.set(key, []); groups.get(key).push(tool); }
  for (const [key, tools] of groups) {
    lines.push(`### ${FAMILIES[key] ?? key}`, "", "| Tool | What it does |", "|---|---|");
    for (const tool of tools) lines.push(`| \`${tool.name}\` | ${esc(firstSentence(tool.description))} |`);
    lines.push("");
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

const [desktop, full] = [await listTools("desktop"), await listTools("full")];
const text = render(desktop, full);

if (!check) { writeFileSync(target, text); console.log(`wrote docs/tools.md (${full.length} tools, ${desktop.length} by default)`); process.exit(0); }

let failed = false;
let current = ""; try { current = readFileSync(target, "utf8"); } catch { /* missing */ }
if (current !== text) { console.error("docs/tools.md is out of date: run npm run docs:tools"); failed = true; }
// Any `family.name` in the docs must be a real tool.
const known = new Set(full.map((tool) => tool.name));
const families = new Set(full.filter((tool) => tool.name.includes(".")).map((tool) => tool.name.split(".")[0]));
const docs = ["README.md", ...readdirSync(path.join(root, "docs")).filter((f) => f.endsWith(".md")).map((f) => `docs/${f}`)];
for (const doc of docs) {
  const body = readFileSync(path.join(root, doc), "utf8");
  for (const match of body.matchAll(/`([a-z]+)\.([a-z_]+)`/g)) {
    const name = `${match[1]}.${match[2]}`;
    if (families.has(match[1]) && !known.has(name)) { console.error(`${doc}: names ${name}, which is not a registered tool`); failed = true; }
  }
}
if (failed) process.exit(1);
console.log("docs are in step with the server");
